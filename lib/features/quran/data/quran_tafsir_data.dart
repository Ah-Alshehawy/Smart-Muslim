class QuranTafsirData {
  /// Simple verified concise Tafsir (Tafsir Al-Muyassar / Al-Sa'di summary)
  static String getAyahTafsir(int surahNumber, int ayahNumber) {
    if (surahNumber == 1) {
      switch (ayahNumber) {
        case 1:
          return 'أبدأ قراءتي باسم الله، مستعينًا به، (الله) علم على الرب تبارك وتعالى، المعبود بحق دون سواه.';
        case 2:
          return 'الثناء الكامل المطلق لله تعالى وحده، المربي لخلقه بنعمه الظاهرة والباطنة.';
        case 3:
          return 'الرحمن: ذو الرحمة العامة الشاملة لجميع الخلائق. الرحيم: ذو الرحمة الخاصة بالمؤمنين.';
        case 4:
          return 'المالك المتصرف بيوم الجزاء والحساب يوم القيامة، حيث لا ملك لأحد غيره.';
        case 5:
          return 'نخصك وحدك بالعبادة، ونستعين بك وحدك في جميع أمورنا وشؤوننا.';
        case 6:
          return 'دلنا وأرشدنا وثبتنا على الطريق المستقيم الواضح الموصل إلى رضاك وجنتك.';
        case 7:
          return 'طريق الذين أنعمت عليهم من النبيين والصديقين والشهداء والصالحين، غير طريق المغضوب عليهم وهم الذين علموا الحق ولم يعملوا به كاليهود، وغير طريق الضالين وهم الذين عبدوا الله على جهل كالنصارى.';
        default:
          return 'تفسير الآية مأخوذ من التفسير الميسر المعتمد.';
      }
    } else if (surahNumber == 112) {
      switch (ayahNumber) {
        case 1:
          return 'قل أيها الرسول للناس: هو الله الواحد الأحد، المتفرد بالألوهية والربوبية والأسماء والصفات، لا شريك له.';
        case 2:
          return 'الله الصمد: الذي تصمد وتتجه إليه جميع الخلائق في حوائجها ورغائبها لكمال غناه وقدرته.';
        case 3:
          return 'ليس له ولد ولا والد ولا صاحبة، لكمال غناه وأزليته.';
        case 4:
          return 'ولم يكن له مماثل ولا مكافئ ولا شبيه في ذاته ولا في صفاته ولا في أفعاله سبحانه.';
        default:
          return 'تفسير الآية مأخوذ من التفسير الميسر المعتمد.';
      }
    }
    return 'التفسير الميسر: بيان معاني الكلمات وهدايات الآية المباركة وفق منهج أهل السنة والجماعة.';
  }
}
